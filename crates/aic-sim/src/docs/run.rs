fn snake(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(c.to_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// One op's source: its doc comment and name, read from the `Op` enum.
pub(super) struct OpDoc {
    section: String,
    pub(super) name: String,
    doc: String,
}

/// Reads `enum Op` from `op.rs`: section comments, doc comments, variants.
pub(super) fn op_docs(src: &str) -> Vec<OpDoc> {
    let body = src
        .split_once("pub enum Op {")
        .expect("enum Op in op.rs")
        .1
        .split_once("\n}\n")
        .expect("enum Op ends")
        .0;
    let (mut out, mut doc, mut section) = (Vec::new(), Vec::<String>::new(), String::new());
    for line in body.lines() {
        let Some(l) = line.strip_prefix("    ") else {
            continue;
        };
        if let Some(s) = l.strip_prefix("// ---------- ") {
            section = s.trim_end_matches(" ----------").to_string();
        } else if let Some(d) = l.strip_prefix("/// ") {
            doc.push(d.to_string());
        } else if l.starts_with(|c: char| c.is_uppercase()) {
            let name: String = l.chars().take_while(|c| c.is_alphanumeric()).collect();
            out.push(OpDoc {
                section: section.clone(),
                name: snake(&name),
                doc: doc.join(" "),
            });
            doc.clear();
        }
    }
    out
}

/// How many times each op is printed in content.
fn op_uses() -> BTreeMap<String, usize> {
    fn walk(v: &serde_json::Value, out: &mut BTreeMap<String, usize>) {
        match v {
            serde_json::Value::Object(o) => {
                if let Some(n) = o.get("op").and_then(|n| n.as_str()) {
                    *out.entry(n.to_string()).or_default() += 1;
                }
                o.values().for_each(|x| walk(x, out));
            }
            serde_json::Value::Array(a) => a.iter().for_each(|x| walk(x, out)),
            _ => {}
        }
    }
    let c = content();
    let mut out = BTreeMap::new();
    fn add<T: serde::Serialize>(ops: &[T], out: &mut BTreeMap<String, usize>) {
        walk(&serde_json::to_value(ops).expect("ops serialize"), out);
    }
    for d in &c.cards {
        add(&d.effects, &mut out);
        add(&d.passives, &mut out);
        for a in d.ability.iter().flat_map(|a| a.branches()) {
            add(&a.effects, &mut out);
        }
    }
    for t in &c.threats {
        add(&t.effects, &mut out);
    }
    for a in &c.adversary {
        add(&a.twists, &mut out);
    }
    for a in &c.alignment {
        for t in &a.tiers {
            add(&t.effects, &mut out);
        }
    }
    for p in &c.projects {
        add(&p.effects, &mut out);
    }
    for p in &c.map.countries {
        let m = &p.megaproject;
        for ops in [&m.player, &m.adversary, &m.converter.effects] {
            add(ops, &mut out);
        }
    }
    for b in &c.ais {
        add(&b.innate.passives, &mut out);
        for u in b.economy_track.iter().chain(&b.play_track) {
            add(&u.effects, &mut out);
            if let Some(c) = &u.capstone {
                add(&c.passives, &mut out);
            }
        }
        for p in &b.powers {
            add(&p.effects, &mut out);
        }
    }
    out
}

fn ops_md(src: &str) -> String {
    let uses = op_uses();
    let mut out = String::from(
        "# Ops\n\nGenerated by `aic-sim docs` from `crates/aic-core/src/op.rs` and `content/`; \
         don't edit. An op is one thing content can print (`{\"op\": \"gain\", ...}`). \
         **Printed** counts it across all content: 0 means rules code with nothing using it yet.\n",
    );
    let mut section = String::new();
    let mut rows = Vec::new();
    let mut flush = |section: &str, rows: &mut Vec<Vec<String>>| {
        if !rows.is_empty() {
            out.push_str(&format!("\n## {section}\n\n"));
            out.push_str(&table(&["Op", "Printed", "What it does"], std::mem::take(rows)));
        }
    };
    for o in op_docs(src) {
        if o.section != section {
            flush(&section, &mut rows);
            section = o.section.clone();
        }
        rows.push(vec![
            format!("`{}`", o.name),
            uses.get(&o.name).copied().unwrap_or(0).to_string(),
            o.doc,
        ]);
    }
    flush(&section, &mut rows);
    out
}

/// Every card's face, one card a line, so a change shows as that card's diff.
fn faces_json() -> String {
    let rows: Vec<String> = content()
        .cards
        .iter()
        .map(|c| {
            let face = serde_json::to_string(&card_face(c)).expect("a face is JSON");
            format!(" {}: {face}", serde_json::to_string(&c.id).expect("an id is JSON"))
        })
        .collect();
    format!("{{\n{}\n}}\n", rows.join(",\n"))
}

const OPEN: &str = "<!-- generated: ";
const CLOSE: &str = "<!-- /generated -->";

/// `text` with every generated block replaced by what `block` says; stops the
/// run on an unknown name.
fn fill(text: &str, block: &dyn Fn(&str) -> Option<String>) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some(i) = rest.find(OPEN) {
        let after = &rest[i + OPEN.len()..];
        let Some(end) = after.find(" -->") else {
            fail("docs: unclosed generated marker")
        };
        let name = &after[..end];
        let Some(body) = block(name) else {
            fail(&format!("docs: unknown generated block {name:?}"))
        };
        let Some(close) = after.find(CLOSE) else {
            fail(&format!("docs: block {name:?} has no {CLOSE}"))
        };
        out.push_str(&rest[..i]);
        out.push_str(&format!("{OPEN}{name} -->\n{body}{CLOSE}"));
        rest = &after[close + CLOSE.len()..];
    }
    out.push_str(rest);
    out
}

/// A generated block's body from the rules.
type Body = fn(&Rules) -> String;

/// Every generated block of `docs/rules/` with its body (182: one table, not a name list and a match); each must
/// stand in exactly one file there.
pub(super) const BLOCKS: [(&str, Body); 21] = [
    ("new_players", new_players_block),
    ("draft_set", |r| draft_set_block(r, content())),
    ("house_terms", |_| house_terms()),
    ("countries", |_| countries_block(content())),
    ("corps", |_| corps_block(content())),
    ("projects", |_| projects_block()),
    ("round_cap", round_cap_block),
    ("adversary", |_| adversary_block()),
    ("difficulty", difficulty_block),
    ("sway_sources", sway_sources_block),
    ("alignment", |_| alignment_block()),
    ("purge_ease", purge_ease_block),
    ("game_end", game_end_block),
    ("standard_actions", standard_actions_block),
    ("boards", |r| boards_block(r, content())),
    ("node_track", |_| node_track_block(content())),
    ("node_track2", |_| node_track2_block(content())),
    ("powers", |_| powers_block(content())),
    ("board_details", |_| board_details_block(content())),
    ("threats", |_| threats_block()),
    ("tunables", tunables_block),
];

/// The body of the generated block `name`, or `None` for an unknown name.
pub(super) fn block(name: &str, r: &Rules) -> Option<String> {
    BLOCKS.iter().find(|(n, _)| *n == name).map(|(_, body)| body(r))
}

/// What is wrong with the rules files (path, text) as a set: a block of [`BLOCKS`] missing or
/// in more than one place, or a file over [`DOC_BUDGET`].
pub(super) fn rules_file_failures(files: &[(String, String)]) -> Vec<String> {
    let mut out = Vec::new();
    for (name, _) in BLOCKS {
        let marker = format!("{OPEN}{name} -->");
        let mut at: Vec<&str> = Vec::new();
        for (p, t) in files {
            for _ in t.matches(&marker) {
                at.push(p);
            }
        }
        if at.len() != 1 {
            out.push(format!("{RULES_DIR}: generated block {name:?} stands {} times, not once ({})", at.len(), at.join(", ")));
        }
    }
    for (path, text) in files {
        if text.len() > DOC_BUDGET {
            out.push(format!("{path}: {} bytes, over the {DOC_BUDGET}-byte doc budget: trim what the code or a generated table already says (no archive files)", text.len()));
        }
    }
    out
}

/// 117: the rules README's "at rules revision N" line, hand-kept, must name `rev`
/// (`RULES_REVISION`): it once said 43 at 45. A missing line is a failure too.
pub(super) fn revision_line_failures(files: &[(String, String)], rev: u32) -> Vec<String> {
    const LEAD: &str = "at rules revision ";
    let Some((path, text)) = files.iter().find(|(p, _)| p.ends_with("README.md")) else {
        return vec![format!("{RULES_DIR}: no README.md")];
    };
    let said: Vec<&str> = text
        .match_indices(LEAD)
        .map(|(i, _)| {
            let rest = &text[i + LEAD.len()..];
            &rest[..rest.find(|c: char| !c.is_ascii_digit()).unwrap_or(rest.len())]
        })
        .collect();
    if said.is_empty() {
        return vec![format!("{path}: no \"{LEAD}N\" line naming RULES_REVISION ({rev})")];
    }
    said.into_iter()
        .filter(|n| *n != rev.to_string())
        .map(|n| format!("{path}: says \"{LEAD}{n}\", but RULES_REVISION is {rev}"))
        .collect()
}

/// 118: a rules file quoting a card, `"words" (Card Name)`, whose face no longer says
/// the words (a card pass changed the number: four such quotes in one hunt). `faces` is
/// (name, full face text). Case and punctuation are ignored.
pub(super) fn card_quote_failures(files: &[(String, String)], faces: &[(String, String)]) -> Vec<String> {
    let norm = |s: &str| {
        let t: String = s.chars().map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { ' ' }).collect();
        t.split_whitespace().collect::<Vec<_>>().join(" ")
    };
    let mut out = Vec::new();
    for (path, text) in files {
        let quotes: Vec<&str> = text.split('"').collect();
        // Odd pieces are inside quotes; the next piece starts with what follows the quote.
        for i in (1..quotes.len().saturating_sub(1)).step_by(2) {
            let (q, after) = (quotes[i], quotes[i + 1].trim_start());
            let Some(names) = after.strip_prefix('(').and_then(|a| a.split(')').next()) else {
                continue;
            };
            // Too short to be a quote, or a pattern ("move up to N"), not a card's words.
            if q.len() < 6 || q.split_whitespace().any(|w| w == "N") {
                continue;
            }
            // A name may wrap across a line.
            let names = names.split_whitespace().collect::<Vec<_>>().join(" ");
            for name in names.split(", ").flat_map(|n| n.split(" and ")).map(str::trim) {
                if let Some((_, face)) = faces.iter().find(|(n, _)| n == name) {
                    if !norm(face).contains(&norm(q)) {
                        out.push(format!("{path}: quotes \"{q}\" ({name}), which its face doesn't say: {face}"));
                    }
                }
            }
        }
    }
    out
}

/// 102: README.md, CLAUDE.md, the web and card-art READMEs (123) and every `docs/*.md` page
/// but those in [`BUDGET_EXEMPT`], with their sizes in bytes (CLAUDE.md's 15 KB a doc;
/// `docs/rules/` is [`rules_file_failures`]'s).
fn budget_pages() -> Vec<(String, usize)> {
    let mut paths: Vec<String> = super::ROOT_DOCS.map(String::from).into();
    if let Ok(dir) = fs::read_dir("docs") {
        let mut pages: Vec<String> = dir
            .flatten()
            .map(|e| e.path())
            .filter(|p| p.extension().and_then(|x| x.to_str()) == Some("md"))
            .map(|p| p.to_string_lossy().replace('\\', "/"))
            .filter(|p| !BUDGET_EXEMPT.contains(&p.as_str()))
            .collect();
        pages.sort();
        paths.extend(pages);
    }
    paths
        .into_iter()
        .filter_map(|p| {
            let n = fs::metadata(&p).ok()?.len() as usize;
            Some((p, n))
        })
        .collect()
}

/// The pages of [`budget_pages`] over [`DOC_BUDGET`].
fn page_budget_failures(pages: &[(String, usize)]) -> Vec<String> {
    pages
        .iter()
        .filter(|(_, n)| *n > DOC_BUDGET)
        .map(|(p, n)| format!("{p}: {n} bytes, over the {DOC_BUDGET}-byte doc budget: trim it"))
        .collect()
}

/// 165: the docs (path, bytes) over [`DOC_WARN`] but within [`DOC_BUDGET`]:
/// a warning, never a failure.
pub(super) fn budget_warnings(sizes: &[(String, usize)]) -> Vec<String> {
    sizes
        .iter()
        .filter(|(_, n)| *n > DOC_WARN && *n <= DOC_BUDGET)
        .map(|(p, n)| {
            format!("warning: {p}: {n} bytes, {} short of the {DOC_BUDGET}-byte doc budget: trim it before adding to it", DOC_BUDGET - n)
        })
        .collect()
}

/// Every `.md` file in `docs/rules/`, sorted, as (path, text).
fn rules_files() -> Vec<(String, String)> {
    let dir = fs::read_dir(RULES_DIR).unwrap_or_else(|e| fail(&format!("{RULES_DIR}: {e}")));
    let mut paths: Vec<String> = dir
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().and_then(|x| x.to_str()) == Some("md"))
        .map(|p| p.to_string_lossy().replace('\\', "/"))
        .collect();
    paths.sort();
    paths
        .into_iter()
        .map(|p| {
            let text = fs::read_to_string(&p).unwrap_or_else(|e| fail(&format!("{p}: {e}")));
            (p, text)
        })
        .collect()
}

/// Dotted names the rules may print that are counters, not tunables or phases.
const COUNTERS: [&str; 1] = ["threats.short"];

/// Bare `snake_case` names the rules may print that are no tunable or op:
/// action names and content fields.
// 105: a trigger's events (`Event` in op.rs) are content words, not ops.
const NOT_TUNABLES: [&str; 8] = ["harden_buy", "harden_chips", "legal_actions", "shared_row", "play_tag", "team_play", "play_cost", "place_tokens"];

/// Backticked `module.name` words in `text` that are no tunable, phase or
/// counter of the baseline, and bare `snake_case` words that are no tunable
/// or name in `ops`.
pub(super) fn unknown_params(text: &str, r: &Rules, ops: &[String]) -> Vec<String> {
    let mut known: Vec<String> = r.tunables().into_iter().map(|t| t.key).collect();
    let modules: Vec<String> = known
        .iter()
        .filter_map(|k| k.split('.').next().map(str::to_string))
        .collect();
    for m in aic_core::describe_modules().as_array().expect("modules") {
        for v in m["variants"].as_array().expect("variants") {
            for p in v["phases"].as_array().expect("phases") {
                known.push(format!("{}.{}", m["id"].as_str().unwrap(), p["name"].as_str().unwrap()));
            }
        }
    }
    known.extend(COUNTERS.iter().map(|c| c.to_string()));
    let mut out = Vec::new();
    for tick in text.split('`').skip(1).step_by(2) {
        if let Some((m, p)) = tick.split_once('.') {
            let word = !p.is_empty() && p.chars().all(|c| c.is_ascii_lowercase() || c == '_' || c.is_ascii_digit());
            if modules.iter().any(|x| x == m) && word && !known.iter().any(|k| k == tick) {
                out.push(tick.to_string());
            }
        } else if tick.contains('_')
            && tick.chars().all(|c| c.is_ascii_lowercase() || c == '_' || c.is_ascii_digit())
            && !NOT_TUNABLES.contains(&tick)
            && !ops.iter().any(|o| o == tick)
            && !known.iter().any(|k| k.split_once('.').is_some_and(|(_, p)| p == tick))
        {
            out.push(tick.to_string());
        }
    }
    out.sort();
    out.dedup();
    out
}

/// What is wrong with `docs/card-pricing-notes.json` (the card viewer's one current pricing line per
/// card id): not an object of strings, or an id that is no player card.
pub(super) fn card_note_failures(text: &str, ids: &[&str]) -> Vec<String> {
    let notes: BTreeMap<String, String> = match serde_json::from_str(text) {
        Ok(n) => n,
        Err(e) => return vec![format!("{CARD_NOTES}: not an object of card id to one line: {e}")],
    };
    let mut out = Vec::new();
    for (id, line) in &notes {
        if !ids.contains(&id.as_str()) {
            out.push(format!("{CARD_NOTES}: {id} is no player card"));
        }
        if line.trim().is_empty() || line.contains('\n') {
            out.push(format!("{CARD_NOTES}: {id} is not one line"));
        }
    }
    out
}

/// Regenerates the docs, or with `--check` reports what is stale.
pub fn run(o: &Options) {
    let r = rules(BASELINE, &load(BASELINE, &[]));
    let src = fs::read_to_string(OP_SOURCE).unwrap_or_else(|e| fail(&format!("{OP_SOURCE}: {e}")));
    let body = |name: &str| block(name, &r);
    let on_disk = |path: &str| fs::read_to_string(path).unwrap_or_default();
    // Path, what it should hold, what it holds.
    let mut files: Vec<(String, String, String)> = vec![
        (FACES_JSON.to_string(), faces_json(), on_disk(FACES_JSON)),
        (OPS_MD.to_string(), ops_md(&src), on_disk(OPS_MD)),
        (HARMS_MD.to_string(), harms_md(&r), on_disk(HARMS_MD)),
        (PLAYER_AID_MD.to_string(), player_aid_md(), on_disk(PLAYER_AID_MD)),
    ];
    let agents_old = on_disk(AGENTS_MD);
    let strategies = |name: &str| (name == "strategies").then(super::blocks::strategies_block);
    files.push((AGENTS_MD.to_string(), fill(&agents_old, &strategies), agents_old));
    let rules_md = rules_files();
    let mut rules_new: Vec<(String, String)> = Vec::new();
    for (path, old) in &rules_md {
        let new = fill(old, &body);
        rules_new.push((path.clone(), new.clone()));
        files.push((path.clone(), new, old.clone()));
    }
    let stale: Vec<&(String, String, String)> = files.iter().filter(|(_, new, old)| new != old).collect();
    let mut failures: Vec<String> = harm_failures().into_iter().map(|f| format!("{HARMS_MD}: {f}")).collect();
    failures.extend(rules_file_failures(&rules_new));
    failures.extend(revision_line_failures(&rules_new, aic_core::RULES_REVISION));
    let faces: Vec<(String, String)> = content().cards.iter().map(|c| (c.name.clone(), card_face(c).full_text())).collect();
    failures.extend(card_quote_failures(&rules_new, &faces));
    let mut sizes = budget_pages();
    failures.extend(page_budget_failures(&sizes));
    for f in &failures {
        eprintln!("{f}");
    }
    sizes.extend(rules_new.iter().map(|(p, t)| (p.clone(), t.len())));
    for w in budget_warnings(&sizes) {
        eprintln!("{w}");
    }
    let mut spelled = super::spelling::failures();
    spelled.extend(super::current_docs::failures());
    let ids: Vec<&str> = content().cards.iter().map(|c| c.id.as_str()).collect();
    spelled.extend(card_note_failures(&on_disk(CARD_NOTES), &ids));
    for s in &spelled {
        eprintln!("{s}");
    }
    if o.check {
        let ops: Vec<String> = op_docs(&src).into_iter().map(|o| o.name).collect();
        let mut bad = 0;
        for (path, text) in &rules_md {
            for b in unknown_params(text, &r, &ops) {
                eprintln!("{path}: `{b}` is not a tunable or an op (docs/architecture.md, *Generated docs*)");
                bad += 1;
            }
        }
        for (path, ..) in &stale {
            eprintln!("{path} is stale: run aic-sim docs");
        }
        let words = super::spelling::stale_failures();
        words.iter().for_each(|s| eprintln!("{s}"));
        if !stale.is_empty() || bad > 0 || !failures.is_empty() || !spelled.is_empty() || !words.is_empty() {
            exit(1);
        }
        return;
    }
    for (path, new, _) in stale {
        fs::write(path, new).unwrap_or_else(|e| fail(&format!("{path}: {e}")));
    }
    // 169: the house words read once the generated docs are written (a stale word there is rewritten above);
    // cards.md is `scripts/cards/cards_doc.py`'s, run after this (regen.py), so only `--check` reads it.
    let words: Vec<String> =
        super::spelling::stale_failures().into_iter().filter(|s| !s.replace('\\', "/").starts_with("docs/cards.md:")).collect();
    words.iter().for_each(|s| eprintln!("{s}"));
    if !failures.is_empty() || !spelled.is_empty() || !words.is_empty() {
        exit(1);
    }
}
