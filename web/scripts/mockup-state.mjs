// 327: the solo screen mockup's state (web/mockup/state.json), captured from a real game: a saved record (`aic-sim
// run configs/solo.json --save DIR --save-when all`) replayed in the dev server's engine to a step of round N's
// action phase, then opened in the player view as the live game. It keeps the view, the legal actions, the map's
// SVG (computed styles inlined, so the mockup draws the real map without the client), and the prompt, phase bar
// and action buttons as the player view words them.
//   node scripts/mockup-state.mjs RECORD [--round 3] [--into 4] [--out mockup/state.json]
// Needs `npm run dev` serving (AIC_URL, default http://localhost:5173/). ~20 s.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { openPage, viewerUrl } from './cdp.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const arg = (name, dflt) => {
  const at = process.argv.indexOf(name);
  return at > 0 ? process.argv[at + 1] : dflt;
};
const recordFile = process.argv[2];
if (!recordFile || recordFile.startsWith('--')) {
  console.error('usage: node scripts/mockup-state.mjs RECORD [--round 3] [--into 4] [--out mockup/state.json]');
  process.exit(2);
}
const ROUND = Number(arg('--round', 3));
const INTO = Number(arg('--into', 4));
const OUT = join(here, '..', arg('--out', 'mockup/state.json'));
const record = JSON.parse(readFileSync(recordFile, 'utf8'));
const ACTION_PHASE = /cards\.play/;

/** In the page: the map's SVG with each element's drawn style written onto it. */
const MAP_SVG = `(() => {
  const svg = [...document.querySelectorAll('svg')].find((s) => s.id === 'board' && s.getBoundingClientRect().width > 0)
    ?? [...document.querySelectorAll('#player svg')].sort((a, b) => b.getBoundingClientRect().width - a.getBoundingClientRect().width)[0];
  const PROPS = ['fill', 'fill-opacity', 'stroke', 'stroke-width', 'stroke-opacity', 'stroke-dasharray', 'opacity', 'font-family', 'font-size', 'font-weight', 'text-anchor', 'dominant-baseline', 'display', 'visibility', 'paint-order', 'stroke-linejoin', 'stroke-linecap'];
  const copy = svg.cloneNode(true);
  const from = [svg, ...svg.querySelectorAll('*')];
  const to = [copy, ...copy.querySelectorAll('*')];
  from.forEach((el, i) => {
    const cs = getComputedStyle(el);
    to[i].setAttribute('style', PROPS.map((p) => p + ':' + cs.getPropertyValue(p)).join(';'));
    to[i].removeAttribute('class');
  });
  const r = svg.getBoundingClientRect();
  if (!copy.getAttribute('viewBox')) copy.setAttribute('viewBox', '0 0 ' + r.width + ' ' + r.height);
  copy.removeAttribute('width');
  copy.removeAttribute('height');
  copy.removeAttribute('id');
  return copy.outerHTML;
})()`;

/** In the page: the prompt, the phase bar and the shown seat's action buttons, as the player view words them. */
const WORDS = `(() => {
  const vis = (e) => e && e.getBoundingClientRect().width > 0;
  const text = (sel) => [...document.querySelectorAll(sel)].filter(vis).map((e) => e.innerText.replace(/\\s+/g, ' ').trim()).filter(Boolean);
  const buttons = [...document.querySelectorAll('#player button')].filter(vis).map((b) => ({ label: b.innerText.replace(/\\s+/g, ' ').trim(), title: b.title || b.dataset.why || '', off: b.disabled || b.classList.contains('shaded') }));
  return { prompt: text('#prompt'), phases: text('#phase-bar > *'), phaseBar: text('#phase-bar'), buttons };
})()`;

const page = await openPage({ width: 1920, height: 1080 });
try {
  await page.send('Page.navigate', { url: viewerUrl });
  await page.until('window.aic && window.aic.view', 'the viewer to start', 240000);
  await page.js(`window.aic.setView('debug')`);
  await page.js(`window.aic.open(${JSON.stringify(JSON.stringify(record))}, 'mockup')`);
  const last = await page.js('window.aic.timeline.last');
  let at = -1;
  for (let i = 0; i <= last; i++) {
    await page.js(`window.aic.seek(${i})`);
    const v = await page.js('({ round: window.aic.view.round, phase: window.aic.view.phase?.name ?? "" })');
    if (v.round === ROUND && ACTION_PHASE.test(v.phase)) { at = i; break; }
  }
  if (at < 0) throw new Error(`no action phase in round ${ROUND}`);
  const step = at + INTO;
  const cut = { ...record, actions: record.actions.slice(0, step), note: `327 mockup: round ${ROUND}, ${INTO} actions into its action phase` };
  delete cut.final_fingerprint;
  delete cut.outcome;
  await page.js(`window.aic.setView('player')`);
  await page.js(`window.aic.open(${JSON.stringify(JSON.stringify(cut))}, 'mockup')`);
  await page.until(`window.aic.timeline.cursor === window.aic.timeline.last`, 'the live game', 10000);
  const state = {
    _note: 'Generated by web/scripts/mockup-state.mjs from a strategist game of configs/solo.json; the mockup (web/mockup.html) reads it.',
    seed: record.seed,
    step,
    view: await page.js('window.aic.view'),
    legal: await page.js('window.aic.legal'),
    words: await page.js(WORDS),
    map: await page.js(MAP_SVG),
  };
  writeFileSync(OUT, `${JSON.stringify(state)}\n`, { encoding: 'utf8' });
  console.log(`mockup-state: seed ${record.seed}, step ${step} (round ${state.view.round}, ${state.view.phase?.name}), ${state.legal.length} legal actions, map ${state.map.length} chars -> ${OUT}`);
} finally {
  await page.close();
}
