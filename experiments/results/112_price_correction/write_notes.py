"""112: the per-card table (prices.md here) and the viewer's pricing note for each repriced card.

Run from the repo root after apply_prices.py and `price_list.py R43 content/cards.json` (so out/price_list.json holds
the r45 column). Writes experiments/results/112_price_correction/prices.md and updates docs/card-pricing-notes.json.
"""
import json

with open('out/price_list.json', encoding='utf-8') as f:
    rows = {r['id']: r for r in json.load(f)}
with open('out/r45_changes.json', encoding='utf-8') as f:
    changes = json.load(f)


def price(p):
    return f'{p[0]} cr, {p[1]} ins'


def pay(r, p):
    keep = 1 if r['tier'] == 1 else 2
    return p[0] + 4 * (keep + p[1]) + r['other']


lines = ['# 112: every repriced card (r43 -> r44 -> r45)', '',
         'Generated by `write_notes.py` (here). The anchor ratio is get / pay at the r45 price, get taken from 111\'s',
         'anchor check (its cards.md, at the r44 effect: a range\'s midpoint), pay = credits + 4 x (keep + play insight)',
         '+ other costs. "r43 ratio" is the r44 effect at the r43 price. The rule is in `apply_prices.py`.', '',
         '| card | tier | r43 | r44 | r45 | ratio at r43 price | r44 ratio | r45 ratio | rule |',
         '|---|---|---|---|---|---|---|---|---|']
notes_path = 'docs/card-pricing-notes.json'
with open(notes_path, encoding='utf-8') as f:
    notes = json.load(f)
for cid in sorted(changes, key=lambda k: rows[k]['name']):
    r = rows[cid]
    p45, why = changes[cid]
    r43 = r['r43']
    at43 = r.get('ratio_at_r43', ['-'])[0] if r43 else '-'
    r44r = round(r['get_lo'] / pay(r, r['r44']), 2)
    r45r = round(r['get_lo'] / pay(r, p45), 2)
    lines.append(f"| {r['name']} | t{r['tier']} | {price(r43) if r43 else 'new'} | {price(r['r44'])} | {price(p45)} | "
                 f"{at43} | {r44r} | {r45r} | {why} |")
    p = pay(r, p45)
    if why.startswith('restored') and r43 and list(p45) == list(r43):
        lead = f"r45 (112): back to r43's price ({price(r43)}; 111 had cut it to {price(r['r44'])} to reach a band)"
    elif why.startswith('partly'):
        lead = (f"r45 (112): {price(p45)}, between r44's {price(r['r44'])} and r43's {price(r43)}: the highest price "
                f"that reads 1.0 with its r44 effect")
    else:
        lead = f"r45 (112): {price(p45)} (from {price(r['r44'])}), over its maximum margin at r44 ({r44r})"
    notes[cid] = f"{lead}; anchors: pay {p:g}; get {r['get_lo']:.1f} = {r45r:.2f}."
lines.append('')
with open('experiments/results/112_price_correction/prices.md', 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(lines))
with open(notes_path, 'w', encoding='utf-8', newline='\n') as f:
    f.write(json.dumps(notes, indent=2, ensure_ascii=False) + '\n')
print(len(changes), 'rows and notes')
