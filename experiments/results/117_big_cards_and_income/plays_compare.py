"""117: share of games each new, changed or big card was offered, kept and played, across the three reads.

    python experiments/results/117_big_cards_and_income/plays_compare.py > experiments/results/117_big_cards_and_income/plays.md

Reads out/read-r45, out/read-income and out/read-r46 (games.jsonl of screen-117-r45 / -income, seeds 34224-34271).
"""

import json
import sys

RUNS = [("r45", "out/read-r45"), ("income", "out/read-income"), ("r46", "out/read-r46")]
CARDS = [
    ("new, early", ["fabrication_megaplex", "frontier_lab_charter", "national_grid_buildout"]),
    ("new, late", ["decapitation_strike"]),
    ("raised, late", ["moonshot_grant"]),
    ("calibrated", ["deep_state_ledger", "dyson_swarm_tranche", "recursive_self_improvement", "kinetic_interdiction",
                    "killswitch_directive", "zero_day_auction", "smart_grid_backbone", "exodus_corridors"]),
    ("existing early, unchanged", ["gigafactory_charter", "wartime_retooling", "multiyear_defense_budget"]),
]


def read(d):
    with open(f"{d}/games.jsonl", encoding="utf-8") as f:
        lines = f.read().splitlines()
    spec = json.loads(lines[0])["spec"]
    agents = [ag for v in spec["variants"] for _ in spec["difficulties"] for ag in spec["agents"]]
    acc = {}
    for ln in lines[1:]:
        g = json.loads(ln)
        ag = agents[g["cell"]]
        n = acc.setdefault(ag, {"n": 0})
        n["n"] += 1
        for cid, r in g["cards"].items():
            e = n.setdefault(cid, [0, 0, 0])
            e[0] += r.get("offered", 0) > 0
            e[1] += (r.get("kept", 0) + r.get("drawn", 0)) > 0
            e[2] += r.get("played", 0) > 0
    return acc


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    with open("content/cards.json", encoding="utf-8") as f:
        names = {c["id"]: c["name"] for c in json.load(f)}
    data = {k: read(d) for k, d in RUNS}
    print("# 117: plays of the new, changed and big cards\n")
    print("Share of games (%), 144 a cell (the three pairs pooled), seeds 34224-34271: offered (dealt into a draft packet "
          "or the opening), kept (kept or drawn), played (at least once). r45 = r45; income = r45's cards at r46's "
          "incomes; r46 = the full r46. Generated by `plays_compare.py`.\n")
    for agent in ("strategist", "greedy"):
        print(f"## {agent}\n")
        print("| card | change | offered r45 / income / r46 | kept | played |")
        print("|---|---|---|---|---|")
        for kind, ids in CARDS:
            for cid in ids:
                cols = []
                for i in range(3):
                    vals = []
                    for k, _ in RUNS:
                        a = data[k][agent]
                        e = a.get(cid)
                        vals.append("-" if e is None and k != "r46" and cid in
                                    ("fabrication_megaplex", "frontier_lab_charter", "national_grid_buildout",
                                     "decapitation_strike") else f"{100 * (e[i] if e else 0) / a['n']:.0f}")
                    cols.append(" / ".join(vals))
                print(f"| {names[cid]} | {kind} | {cols[0]} | {cols[1]} | {cols[2]} |")
        print()


if __name__ == "__main__":
    main()
