"""Generates docs/cards.md from content/cards.json, and checks the set's shape.

    python scripts/cards/cards_doc.py           # writes docs/cards.md, prints the shape
    python scripts/cards/cards_doc.py --check   # exits 1 if docs/cards.md is stale

Cards are listed by primary tag (the first printed tag), then tier, then name. The shape table compares the draft decks with the
set's targets (written in `shape`). The Rust test `crates/aic-sim/tests/docs.rs` reads
the output for "Rules revision N" and every card name: keep both.
"""
import collections
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TAGS = ['science', 'industry', 'cyber', 'power', 'diplomacy', 'security']
KINDS = ['program', 'building', 'event']


def revision():
    with open(os.path.join(ROOT, 'crates', 'aic-core', 'src', 'lib.rs'), encoding='utf-8') as f:
        return re.search(r'RULES_REVISION: u32 = (\d+)', f.read())[1]


def load():
    with open(os.path.join(ROOT, 'content', 'cards.json'), encoding='utf-8') as f:
        return json.load(f)


def load_faces():
    """Each card's generated face (`aic-sim docs` writes web/card/faces.json)."""
    with open(os.path.join(ROOT, 'web', 'card', 'faces.json'), encoding='utf-8') as f:
        return json.load(f)


def face_text(face):
    return ' '.join(t for t in (face['top_text'], face['text']) if t)


def cards_module():
    """The baseline config's cards module, if it has one."""
    with open(os.path.join(ROOT, 'configs', 'baseline.json'), encoding='utf-8') as f:
        cfg = json.load(f)
    return next((m for m in cfg['modules'] if m['module'] == 'cards'), None)


def deck_ids():
    m = cards_module()
    return set(m['cards']) if m else set()


def cost_text(c):
    parts = [f"{c.get('cost', 0)} cr"]
    for k, short in [('energy', 'en'), ('chips', 'ch'), ('antimatter', 'am'), ('research_cubes', 'rc')]:
        if c.get(k):
            parts.append(f'{c[k]} {short}')
    for r, n in c.get('lowers', []):
        parts.append(f'-{n} {r} income')
    if c.get('needs'):
        parts.append('needs ' + ', '.join(f'{n} {t}' for t, n in c['needs']))
    if c.get('replaces'):
        parts.append(f"over {c['replaces']}")
    return '; '.join(parts)


def pct(n, d):
    return f'{100 * n / d:.0f}%' if d else '-'


def shape(cards):
    deck = [c for c in cards if c['tier'] in (1, 2)]
    n = len(deck)

    def split(pred, values):
        return ' / '.join(pct(sum(pred(c, v) for c in deck), n) for v in values)

    out = ['| measure | draft decks | target |', '|---|---|---|']
    out.append(f'| cards | {n} | ~150 |')
    out.append('| tier 1 / 2 | ' + ' / '.join(
        str(sum(c['tier'] == t for c in deck)) for t in (1, 2)) + ' | ~110 / ~40 |')
    out.append('| program / building / event | '
               + split(lambda c, v: c['kind'] == v, KINDS) + ' | 60 / 25 / 15% |')
    out.append('| 1 / 2 / 3 tags | '
               + split(lambda c, v: len(c['tags']) == v, (1, 2, 3)) + ' | 60 / 30 / 10% |')
    out.append('| insight 0 / 1 / 2 | '
               + split(lambda c, v: c.get('insight', 0) == v, (0, 1, 2)) + ' | 25 / 50 / 25% |')
    k = sum('help' in c.get('keywords', []) for c in deck)
    out.append(f'| help cards | {pct(k, n)} | ~10% |')
    prim = ', '.join(f"{sum(c['tags'][0] == t for c in deck)} ({sum(t in c['tags'] for c in deck)})"
                     for t in TAGS)
    out.append(f"| primary (any) per tag: {', '.join(TAGS)} | {prim} | ~25 each |")
    big = sum(c.get('cost', 0) >= 25 for c in deck)
    out.append(f'| credits 25+ | {big} | a handful, none over ~50 |')
    am = sum(bool(c.get('antimatter')) for c in deck)
    out.append(f'| antimatter cost | {am} | tier-2 ultimates only |')
    return '\n'.join(out)


def render(cards):
    deck = deck_ids()
    params = cards_module()['params']
    lines = [
        '# The player cards',
        '',
        'Generated by `python scripts/cards/cards_doc.py` from `content/cards.json`: do not',
        f'edit by hand. Rules revision {revision()}. Every card is a **candidate**. One section',
        'per primary tag (the first printed tag; *other tags* lists the rest), sorted by tier',
        'then name. Cost: credits (cr), energy (en),',
        'chips (ch), antimatter (am), research cubes (rc), income lowered for the game, tags needed on your cards in',
        'play, and the tag of the building a replacement goes *over*. Insight is the cost to',
        f"play; keeping a drafted card costs {params['keep_tier1']} (tier 1) or {params['keep_tier2']} (tier 2) more.",
        '*(not in deck)*: in the content, not in the baseline config.',
        '',
        '## Shape',
        '',
        # 111: the shape is the draft decks' (the baseline's cards), not every card in the content.
        shape([c for c in cards if c['id'] in deck] if deck else cards),
        '',
    ]
    def key(c):
        prim = TAGS.index(c['tags'][0]) if c['tags'] else 9
        return (prim, c['tier'], c['name'])
    faces = load_faces()
    groups = collections.OrderedDict()
    for c in sorted(cards, key=key):
        g = c['tags'][0].capitalize()
        groups.setdefault(g, []).append(c)
    for g, cs in groups.items():
        lines += [f'## {g} ({len(cs)})', '',
                  '| card | tier | kind | cost | insight | other tags | effect |',
                  '|---|---|---|---|---|---|---|']
        for c in cs:
            tags = ', '.join(c['tags'][1:]) or '-'
            name = c['name']
            if c['id'] not in deck:
                name += ' *(not in deck)*'
            kw = c.get('keywords', [])
            kind = c['kind'] + (' (help)' if 'help' in kw else '')
            text = face_text(faces[c['id']]).replace('|', '/')
            lines.append(
                f"| {name} | {c['tier'] or '-'} | {kind} | {cost_text(c)} | "
                f"{c.get('insight', 0)} | {tags} | {text} |")
        lines.append('')
    lines += alignment_section()
    return '\n'.join(lines)


def alignment_section():
    """156: the Unity and Discord cards, three tiers each (too long for rules/alignment.md's budget)."""
    with open(os.path.join(ROOT, 'content', 'alignment.json'), encoding='utf-8') as f:
        cards = json.load(f)
    out = ['## Unity and Discord cards', '',
           'From `content/alignment.json`. Its side\'s tips before this tip pick the tier that resolves '
           '(`alignment.tier_at`; [rules/alignment.md](rules/alignment.md)). *(draft)*: drafted by 156, for Matt to keep or prune.',
           '']
    for side in ('unity', 'discord'):
        cs = [c for c in cards if c['side'] == side]
        out += [f'### {side.capitalize()} ({len(cs)})', '',
                '| card | tier I | tier II | tier III |', '|---|---|---|---|']
        for c in cs:
            name = c['name'] + (' *(draft)*' if c.get('draft') else '')
            t = [x['text'].replace('|', '/') for x in c['tiers']]
            out.append(f"| {name} | {t[0]} | {t[1]} | {t[2]} |")
        out.append('')
    return out


def main(argv):
    cards = load()
    text = render(cards)
    path = os.path.join(ROOT, 'docs', 'cards.md')
    if '--check' in argv:
        with open(path, encoding='utf-8') as f:
            if f.read() != text:
                print('docs/cards.md is stale: run python scripts/cards/cards_doc.py')
                return 1
        return 0
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print(shape(cards))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
